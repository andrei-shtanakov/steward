#!/bin/sh
# Собрать курируемый пакет контекста для ревьюера ИЗ BASE-РЕВИЗИИ.
#
# И список файлов, и их содержимое читаются через `git show <base>:<путь>` —
# никогда из рабочего дерева. Разница не косметическая: дерево можно подменить
# любым шагом workflow до нас, а `<base>` называет ревизию, в которую вливают,
# и её содержимое автор PR изменить не может. Его правки этих же файлов
# ревьюер увидит дифом, рядом с базовой версией — то есть как предложение, а не
# как данность.
#
# Коды выхода: 0 — пакет собран; 2 — отказ (манифест сломан, файл не читается,
# превышен лимит); 3 — манифест в base отсутствует, то есть контекст здесь просто
# не настроен. Отказы ГРОМКИЕ: пакет, тихо усохший до нуля, вернул бы ревьюера к
# прежнему режиму «вижу только диф», но уже незаметно — вердикт выглядел бы
# вынесенным с контекстом.
set -eu

usage() {
    echo "usage: collect-context.sh --base <sha> --manifest <path> [--max-file N] [--max-total N]" >&2
}

#: Потолки байт. Смысл не в экономии токенов, а в предсказуемости: пакет,
#: способный вырасти неограниченно, однажды вытеснит из промпта сам диф.
max_file=65536
max_total=262144

base=""
manifest=""

while [ $# -gt 0 ]; do
    case "$1" in
        --base)      [ $# -ge 2 ] || { usage; exit 2; }; base="$2"; shift 2 ;;
        --manifest)  [ $# -ge 2 ] || { usage; exit 2; }; manifest="$2"; shift 2 ;;
        --max-file)  [ $# -ge 2 ] || { usage; exit 2; }; max_file="$2"; shift 2 ;;
        --max-total) [ $# -ge 2 ] || { usage; exit 2; }; max_total="$2"; shift 2 ;;
        *) usage; exit 2 ;;
    esac
done

[ -n "$base" ] || { usage; exit 2; }
[ -n "$manifest" ] || { usage; exit 2; }

digest() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum | cut -d' ' -f1
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 | cut -d' ' -f1
    else
        echo "нет ни sha256sum, ни shasum — не могу посчитать отпечаток." >&2
        exit 2
    fi
}

# «Манифеста нет» и «манифест есть, но сломан» — разные состояния, и мерить их
# одним отказом нельзя. `git show` падает одинаково на отсутствующем пути и на
# неразрешимом base, поэтому сначала проверяем саму ревизию: если base не
# разрешается, это поломка вызывающего (код 2). И только когда ревизия заведомо
# на месте, отсутствие пути в её дереве означает «контекст в этом репозитории не
# настроен» — код 3, отдельный от отказа.
#
# Различие не теоретическое: у PR, который САМ добавляет манифест, в base его
# ещё нет. Без кода 3 такой PR не смог бы позеленеть — фича блокировала бы
# собственное внедрение.
git rev-parse --verify --quiet "$base^{commit}" >/dev/null || {
    echo "base-ревизия не разрешается: $base" >&2
    exit 2
}
if ! git cat-file -e "$base:$manifest" 2>/dev/null; then
    echo "манифест контекста отсутствует в base ($base:$manifest)" >&2
    echo "курируемый контекст в этом репозитории не настроен." >&2
    exit 3
fi
manifest_text=$(git show "$base:$manifest" 2>/dev/null) || {
    echo "манифест контекста не читается из base: $base:$manifest" >&2
    exit 2
}

# Возврат каретки как отдельная переменная: манифест, закоммиченный с
# CRLF-окончаниями, оставил бы `\r` в конце пути, и `git show` искал бы блоб с
# этим символом в имени — отказ на существующем файле, красный чек на каждом PR
# до тех пор, пока кто-то не перепишет файл в LF.
CR=$(printf '\r')

tmp=$(mktemp)
blob=$(mktemp)
trap 'rm -f "$tmp" "$blob"' EXIT

# `printf '%s\n'` вместо here-string: последний есть в bash, но не в POSIX sh,
# а этот скрипт гоняется и под dash в CI.
printf '%s\n' "$manifest_text" | while IFS= read -r line; do
    line=${line%"$CR"}
    case "$line" in
        ''|'#'*) continue ;;
    esac
    path="$line"

    # Путь обязан быть внутри репозитория и назван буквально. `..` и абсолютный
    # путь отвергаются здесь, а не полагаются на `git show`: тот и сам их не
    # выпустит наружу дерева, но отказ должен объяснять, что именно неверно.
    # Метасимволы glob'а отвергаются как путь, а не разворачиваются: список
    # обязан называть каждый файл, иначе расширение пакета перестаёт проходить
    # ревью — новый файл в репозитории молча попадал бы под шаблон.
    case "$path" in
        /*|*..*|*'*'*|*'?'*|*'['*)
            echo "недопустимый путь в манифесте: $path" >&2
            exit 2
            ;;
    esac

    # Содержимое кладём В ФАЙЛ, а не в переменную: `$(...)` съедает хвостовые
    # переводы строк, и тогда приложенный текст перестал бы быть побайтовой
    # копией блоба, а отпечаток — сходиться с проверкой вручную
    # (`git show <base>:<путь> | sha256sum`). Отпечаток, который нельзя
    # перепроверить, не доказывает ничего.
    # Тип объекта проверяется ДО чтения: `git show <base>:<каталог>` выходит с
    # нулём и печатает листинг дерева. Без этой проверки каталог в манифесте
    # приложился бы как «файл» — с заголовком, отпечатком и зелёным чеком, но
    # вместо кода модуля ревьюер получил бы перечень имён. Ровно тот класс
    # «контекст приложен без обещанного эффекта», который кит ловит у других.
    kind=$(git cat-file -t "$base:$path" 2>/dev/null) || {
        echo "файл контекста не читается из base: $base:$path" >&2
        exit 2
    }
    if [ "$kind" != "blob" ]; then
        echo "путь в манифесте — не файл, а $kind: $path" >&2
        exit 2
    fi
    git show "$base:$path" > "$blob" 2>/dev/null || {
        echo "файл контекста не читается из base: $base:$path" >&2
        exit 2
    }

    # Бинарь ловим по NUL-байту, сравнивая длину до и после его вырезания:
    # `grep` на NUL ведёт себя по-разному между реализациями, `tr` — нет.
    # Промпт это текст; бинарное содержимое в нём либо потеряется, либо порвёт
    # разметку, и ревьюер получит не то, что заявлено.
    size=$(wc -c < "$blob" | tr -d ' ')
    stripped=$(tr -d '\000' < "$blob" | wc -c | tr -d ' ')
    if [ "$size" != "$stripped" ]; then
        echo "файл контекста не текстовый (содержит NUL): $path" >&2
        exit 2
    fi

    if [ "$size" -gt "$max_file" ]; then
        echo "файл контекста больше $max_file байт ($size): $path" >&2
        exit 2
    fi

    # Путь И отпечаток рядом с содержимым: ревьюер должен уметь сослаться на
    # конкретный файл, а отпечаток делает проверяемым, ЧТО именно ему дали —
    # ровно `git show <base>:<путь> | sha256sum`, без поправок.
    #
    # Форма заголовка — `--- ФАЙЛ … ---`, в стиле остальных маркеров кита, а не
    # markdown'ный `### `: живой прогон показал, что приложенный README сам
    # содержит строки `### Матрица полей …`, и ревьюер прочёл бы их как границу
    # файла. Содержимое base доверенное (прошло ревью), поэтому суффикс-хеш, как
    # у дифа, здесь избыточен — достаточно формы, не встречающейся в прозе.
    sha=$(digest < "$blob")
    printf -- '--- ФАЙЛ %s sha256:%s ---\n' "$path" "$sha"
    cat "$blob"
    printf '\n'
done > "$tmp"

# `exit 2` из тела цикла доходит сюда сам: подоболочка завершает конвейер, и
# `set -e` роняет скрипт. А вот пустой результат так не ловится — манифест из
# одних комментариев прошёл бы с кодом 0. Проверяем отдельно: молча пустой пакет
# вернул бы ревьюера к режиму «вижу только диф», но уже под видом ревью с
# контекстом.
if [ ! -s "$tmp" ]; then
    echo "пакет контекста пуст — манифест не дал ни одного файла" >&2
    exit 2
fi

# Потолок меряется по ФАКТИЧЕСКИ собранным байтам, а не по сумме длин блобов:
# заголовки и разделители тоже занимают место в промпте, и на манифесте из тысяч
# крошечных файлов именно они составили бы почти весь пакет. Сумма блобов сказала
# бы «уложились», пока пакет вытесняет из промпта сам диф.
collected=$(wc -c < "$tmp" | tr -d ' ')
if [ "$collected" -gt "$max_total" ]; then
    echo "пакет контекста больше $max_total байт (собрано $collected)" >&2
    exit 2
fi

cat "$tmp"
