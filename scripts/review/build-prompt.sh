#!/bin/sh
# Склейка инструкций ревьюера с дифом. Оба приходят ФАЙЛАМИ и склеиваются
# через `cat`: диф никогда не попадает ни в аргумент командной строки, ни в
# подстановку выражений — иначе его содержимое интерпретировалось бы как часть
# команды, а диф это недоверенный текст.
set -eu

usage() {
    echo "usage: build-prompt.sh --prompt <file> --diff <file>" \
        "[--context <file>]" >&2
}

# Маркер конца зоны недоверенных данных обязан быть непредсказуем для самого
# дифа: литеральная строка (`@id:review-kit-diff-marker-hardening`, снято
# владельцем — гейт нашёл живой обход) позволяла патчу вставить собственный
# "конец дифа" и вывести хвост на верхний уровень промпта, откуда ревьюер
# читает инструкции как доверенные. Суффикс — первые 12 hex-символов sha256
# ОТ ВСЕГО СОДЕРЖИМОГО ДИФА, детерминированный (один и тот же вход — один и
# тот же суффикс, тесты воспроизводимы) и цикличный по построению: чтобы
# подделать закрывающий маркер, патч обязан заранее знать хеш своего
# собственного содержимого ПОСЛЕ вставки подделки — самоссылающийся поиск,
# для которого угадывание практически не работает.
hash_diff() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -c1-12
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | cut -c1-12
    else
        echo "нет ни sha256sum, ни shasum — не могу построить маркер." >&2
        exit 2
    fi
}

prompt=""
diff=""
# Контекст необязателен: репозиторий без манифеста ревьюируется как прежде, по
# одному дифу. Обязательность живёт не здесь, а у вызывающего — он уже знает,
# настроен манифест или нет (код 3 от collect-context.sh).
context=""

while [ $# -gt 0 ]; do
    case "$1" in
        # Голый флаг без значения (нет $2) — ошибка конфигурации, а не молчаливый
        # сдвиг мимо края позиционных параметров: без сторожа `shift 2` на bash
        # молча съедает лишнее (exit 1), а на dash падает с сообщением самого
        # shell мимо usage() — платформозависимое поведение опаснее прямого exit 2.
        --prompt) [ $# -ge 2 ] || { usage; exit 2; }; prompt="$2"; shift 2 ;;
        --diff)   [ $# -ge 2 ] || { usage; exit 2; }; diff="$2"; shift 2 ;;
        --context) [ $# -ge 2 ] || { usage; exit 2; }; context="$2"; shift 2 ;;
        *) usage; exit 2 ;;
    esac
done

[ -n "$prompt" ] || { usage; exit 2; }
[ -n "$diff" ] || { usage; exit 2; }
[ -f "$prompt" ] || { echo "нет файла инструкций: $prompt" >&2; exit 2; }
[ -f "$diff" ] || { echo "нет файла дифа: $diff" >&2; exit 2; }
# `-f` проверяет существование, не читаемость: без прав на чтение `cat` ниже
# упал бы под `set -e` кодом 1 — а 1 через local.sh доезжает до хука как
# "найдены находки уровня blocker/major", и пуш заблокировался бы так, будто
# ревью нашло дефект в патче, хотя сломаны права на локальный файл.
[ -r "$prompt" ] || { echo "файл инструкций нечитаем: $prompt" >&2; exit 2; }
[ -r "$diff" ] || { echo "файл дифа нечитаем: $diff" >&2; exit 2; }
if [ -n "$context" ]; then
    [ -f "$context" ] || { echo "нет файла контекста: $context" >&2; exit 2; }
    [ -r "$context" ] || { echo "файл контекста нечитаем: $context" >&2; exit 2; }
fi

marker=$(hash_diff "$diff")

cat "$prompt"

# Контекст идёт ПЕРЕД дифом и в собственных маркерах. Он куда доверенней дифа —
# это содержимое base, прошедшее ревью, — но своя рамка нужна не ради недоверия,
# а чтобы граница между «как есть в целевой ветке» и «что предлагает патч»
# оставалась читаемой: без неё ревьюер не отличит текущий код от предложенного и
# начнёт находить дефекты в том, что уже смержено.
if [ -n "$context" ]; then
    ctx_marker=$(hash_diff "$context")
    printf '\n\n--- КОНТЕКСТ ИЗ BASE НАЧАЛО %s ---\n' "$ctx_marker"
    cat "$context"
    printf '\n--- КОНТЕКСТ ИЗ BASE КОНЕЦ %s ---\n' "$ctx_marker"
fi

printf '\n\n--- ДИФ НАЧАЛО %s ---\n' "$marker"
cat "$diff"
printf '\n--- ДИФ КОНЕЦ %s ---\n' "$marker"
